    def _format_current_predicate_state(self, scene_graph: TaskSceneGraph):
        predicates = []
        for pred in sorted(scene_graph.simulator.state, key=lambda pred: repr(pred)):
            targets = [obj.value for obj in pred.assignment]
            if targets:
                predicates.append(f"({pred.name.value} {' '.join(targets)})")
            else:
                predicates.append(f"({pred.name.value})")
        return "\n".join(predicates)


    def _verify_skill_completion(self, llm_response, image_rgb, skill: str, scene_graph: TaskSceneGraph):
        """
        Use a VLM to verify whether the observation shows that the claimed skill
        has actually been completed, conditioned on the current symbolic state.
        """
        current_scene_graph_json = json.dumps(
            scene_graph.to_dict(include_grounding=False),
            indent=2,
        )
        current_predicates = self._format_current_predicate_state(scene_graph)

        # print("current_scene_graph_json-----------> ", current_scene_graph_json)
        # print("current_predicates-----------> ", current_predicates)

        user_prompt = VLAVerifier.SKILL_COMPLETION_VERIFIER_USER_TEMPLATE.format(
            scene_graph_json=current_scene_graph_json,
            current_predicates=current_predicates,
            skill=skill,
        )
        t0 = time.monotonic()
        print(f"  [VLM] Querying VLM for skill completion verification...")
        yield [transformers_api.make_message(texts=[user_prompt], images=[image_rgb])]

        raw_response = llm_response['content']
        try:
            result = extract_json_from_response(raw_response)
        except (json.JSONDecodeError, ValueError) as e:
            print(f"  [VLM] WARNING: Failed to parse response: {e}")
            print(f"  [VLM] Raw: {raw_response[:500]}")
            yield SubtaskVerificationResult(
                subtask=skill,
                accepted=False,
                reasoning=f"VLM returned unparseable response: {str(e)}",
                grounded_action=None,
            )
            return
        t1 = time.monotonic()
        print(f"  [VLM] Time elapsed: {t1 - t0}")

        completed_flag = result.get("skill_completed")
        if isinstance(completed_flag, str):
            normalized = completed_flag.strip().lower()
            if normalized in {"true", "completed", "yes"}:
                completed_flag = True
            elif normalized in {"false", "not_completed", "not completed", "no"}:
                completed_flag = False
        if not isinstance(completed_flag, bool):
            completed_flag = False

        yield SubtaskVerificationResult(
            subtask=skill,
            accepted=completed_flag,
            reasoning=result.get("reason", "<No reasoning output>"),
            grounded_action=None,
        )
