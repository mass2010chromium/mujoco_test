    def _parse_plan_steps(self, raw_plan):

        text = raw_plan.strip()
        if not text:
            return []

        numbered_matches = list(re.finditer(r"(?:^|\s)(\d+)\.\s*", text))
        if numbered_matches:
            steps = []
            for i, match in enumerate(numbered_matches):
                start = match.end()
                end = (
                    numbered_matches[i + 1].start()
                    if i + 1 < len(numbered_matches)
                    else len(text)
                )
                step_text = text[start:end].strip(" \n\t;")
                if step_text:
                    steps.append(step_text)
            if steps:
                return steps

        return [
            chunk.strip(" \n\t-")
            for chunk in re.split(r"[\n;]+", text)
            if chunk.strip()
        ]


    def _normalize_grounded_action(self, action_obj: dict):
        """
        Normalize a grounded action produced from LLM
        """
        name = action_obj.get("name")
        params = action_obj.get("parameters", [])
        if not isinstance(name, str) or not isinstance(params, list):
            return None
        if not all(isinstance(x, str) for x in params):
            return None
        return name.strip(), [x.strip() for x in params]


    def verify_skill_plan(self, plan):
        """
        Verify a multi-step plan by translating each step and forward-simulating
        grounded PDDL actions on a temporary simulator.

        Args:
            plan: Either a numbered string plan (e.g., "1. ... 2. ...")

        Returns:
            dict with keys:
                feasible (bool),
                failed_step (int | None),
                failure_reason (str | None),
                steps (list[str]),
                applied_actions (list[str]),
                step_results (list[SubtaskVerificationResult]).
        """
        steps = self._parse_plan_steps(plan)
        if not steps:
            raise ValueError("verify_plan received an empty plan.")

        step_results = []
        applied_actions = []

        copy_scene_graph = copy.deepcopy(self.scene_graph)

        for step_idx, skill in enumerate(steps, start=1):
            print(f"[PLAN] Step {step_idx}/{len(steps)}: {skill}")

            result = self.verify_skill(skill)
            step_results.append(result)

            if not result.accepted:
                reason = result.reasoning
                print(f"[PLAN] FAILED at step {step_idx}: {reason}")
                # self.scene_graph.reset_simulator()
                self.scene_graph = copy_scene_graph
                return {
                    "feasible": False,
                    "failed_step": step_idx,
                    "failure_reason": reason,
                    "steps": steps,
                    "applied_actions": applied_actions,
                    "step_results": step_results,
                }

            action_name, action_params = self._normalize_grounded_action(result.grounded_action)
            matched_action = self.scene_graph.match_grounded_action(
                action_name,
                action_params,
            )
            if matched_action is None:
                reason = (
                    "Translator returned an action that is not available in the "
                    f"current symbolic state: {action_name}({', '.join(action_params)})"
                )
                print(f"[PLAN] FAILED at step {step_idx}: {reason}")
                # self.scene_graph.reset_simulator()
                self.scene_graph = copy_scene_graph
                return {
                    "feasible": False,
                    "failed_step": step_idx,
                    "failure_reason": reason,
                    "steps": steps,
                    "applied_actions": applied_actions,
                    "step_results": step_results,
                }

            self.scene_graph.apply_action(matched_action)

            applied_str = f"{action_name}({', '.join(action_params)})"
            applied_actions.append(applied_str)
            print(f"[PLAN] Applied: {applied_str}")

        print(f"[PLAN] SUCCESS: all {len(steps)} steps are symbolically feasible.")

        # Restore simulator so repeated calls always start from the same baseline.
        # self.scene_graph.reset_simulator()
        self.scene_graph = copy_scene_graph

        return {
            "feasible": True,
            "failed_step": None,
            "failure_reason": None,
            "steps": steps,
            "applied_actions": applied_actions,
            "step_results": step_results,
        }
    
    
    def set_skill_plan(self, plan: str):
        """
        parse a string skill plan into an ordered list of skills to be executed sequentially
        """
        self.skill_plan = self._parse_plan_steps(plan)
        self.current_skill = None

    
    def verify_skill_transition(self, next_skill: str, image_rgb=None):
        """
        ASSUME: the skill plan has already been verified, and thus has to be executed sequentially (no forward/backward jumps)

        verification 1: the next skill must be the next skill in the planned skills list (i.e. sequential execution)
        verification 2: if an image is provided, verify with a VLM that the previously active skill is truly completed
        if both verifications passed, transition verification suceeds, forward simulate scene graph, and pop the skill from the planned skills list
        if either verification fails, verification fails, no change to scene graph or skill plan
        Returns:
            dict with keys:
                feasible (bool),
                failure_reason (str | None),
        """
        # sanity check: no skill plan is set
        if not self.skill_plan:
            return {
                "feasible": False,
                "failure_reason": "No remaining skill plan is set",
            }

        # verification 1: the next skill must be the next skill in the planned skills list
        if next_skill != self.skill_plan[0]:
            return {
                "feasible": False,
                "failure_reason": f"Next skill is not the next skill in the planned skills list: {next_skill} != {self.skill_plan[0]}",
            }
        
        # verification 2: if we have an observation, verify that the previous skill is visually complete before accepting the transition.
        if self.current_skill is not None and image_rgb is not None:
            completion_result = self.verify_skill_completion(
                image_rgb=image_rgb,
                skill=self.current_skill,
                scene_graph=self.scene_graph)

            if not completion_result.accepted:
                return {
                    "feasible": False,
                    "failure_reason": (
                        f"Skill completion check failed for {self.current_skill}: "
                        f"{completion_result.reasoning}"
                    ),
                }
        
        # if both verifications passed, verification suceeds, forward simulate scene graph, and pop the skill from the planned skills list
        result = self.verify_skill(next_skill)  # call verify_skill to get the grounded pddl action
        if not result.accepted:
            reason = result.reasoning
            self.scene_graph.reset_simulator()
            return {
                "feasible": False,
                "failure_reason": reason,
            }

        action_name, action_params = self._normalize_grounded_action(result.grounded_action)
        matched_action = self.scene_graph.match_grounded_action(
            action_name,
            action_params,
        )
        self.scene_graph.apply_action(matched_action)

        self.skill_plan.pop(0)
        self.current_skill = next_skill

        return {
            "feasible": True,
            "failure_reason": None,
        }
