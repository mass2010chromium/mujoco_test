"""
First-layer verification pipeline for VLA subtask verification using scene graphs.

This module ties together the scene graph, DSL, and LLM translator to provide
a complete verification pipeline for reasoning VLA models like pi0.5.

Pipeline:
  1. Construct a scene graph from an initial scene image (VLM, one-time).
  2. For each generated subtask from the VLA:
     a. Translate subtask -> PDDL action (LLM, text-only).
     b. Verify PDDL action preconditions against scene graph state.
     c. If accepted: apply effects -> produce successor scene graph.
     d. If rejected: return feedback with reasons.

Design principles:
  - After initial construction, all verification is language-only (no vision).
  - Scene graph acts as a symbolic world model (SayPlan-style).
  - Actions are state transitions with pre/postconditions.
"""

from dataclasses import dataclass
import json
import textwrap
import time

import numpy as np

from llm_apis.llm_tool import extract_json_from_response
from llm_apis import transformers_api

from .scene_graph import TaskSceneGraph

@dataclass
class SubtaskVerificationResult:
    """Complete result of verifying a single subtask."""
    subtask: str
    accepted: bool
    reasoning: str
    grounded_action: str = None

    def summary(self) -> str:
        status = "ACCEPTED" if self.accepted else "REJECTED"
        lines = [
            f"Subtask: \"{self.subtask}\"",
            f"Status: {status}",
            f"Action: {self.grounded_action}",
        ]
        lines.append(f"Translator Reasoning: {self.reasoning}")
        return "\n".join(lines)


class VLAVerifier:
    """
    First-layer verification pipeline for VLA-generated subtasks.

    Uses scene graphs as a symbolic world model to verify whether textual
    subtasks generated by a reasoning VLA (e.g., pi0.5) are feasible.
    """

    def __init__(self, scene_graph: TaskSceneGraph, llm_interface):
        self.scene_graph = scene_graph

        # Dynamically build VLM and LLM requiring functions.
        self.translate_subtask = llm_interface(
            self._translate_subtask,
            system_prompt=VLAVerifier.TRANSLATOR_SYSTEM_PROMPT.format(pddl_domain=scene_graph.pddl_domain_desc)
        )

    def _translate_subtask(self, llm_response, subtask: str, scene_graph: TaskSceneGraph):
        # TODO: rewrite
        """
        Translate a natural language subtask into a DSL action using an LLM.

        The LLM receives only text (scene graph JSON + subtask string),
        ensuring the first-layer verification is purely language-based.

        Args:
            subtask: Natural language subtask from VLA model.

        Returns:
            SubtaskVerificationResult -- the translated action (or INVALID with reasoning).
        """

        avail_actions = json.dumps(self.scene_graph.get_available_actions(), indent=2)

        user_prompt = VLAVerifier.TRANSLATOR_USER_TEMPLATE.format(
            scene_graph_json=json.dumps(scene_graph.to_dict(include_grounding=False), indent=2),
            subtask=subtask,
            avail_actions=avail_actions
        )
        t0 = time.monotonic()
        print(f"  [LLM] Querying LLM for subtask translation...")
        yield [ transformers_api.make_message(user_prompt) ]

        raw_response = llm_response['content']
        try:
            result = extract_json_from_response(raw_response)
        except (json.JSONDecodeError, ValueError) as e:
            print(f"  [LLM] WARNING: Failed to parse response: {e}")
            print(f"  [LLM] Raw: {raw_response[:500]}")
            yield SubtaskVerificationResult(
                subtask=subtask,
                accepted=False,
                reasoning=f"LLM returned unparseable response: {str(e)}",
                grounded_action="<No action output>"
            )
        t1 = time.monotonic()
        print(f"  [LLM] Time elapsed: {t1 - t0}")

        yield SubtaskVerificationResult(
            subtask=subtask,
            accepted=result['status'].strip().lower() == 'success',
            reasoning=result.get("reason", "<No reasoning output>"),
            grounded_action=result.get("chosen_action", "<No action output>")
        )
    TRANSLATOR_SYSTEM_PROMPT = textwrap.dedent("""\
    You are a robot action translator for a manipulation verification system. \
    Your job is to convert natural language subtask descriptions into formal, \
    verifiable actions in PDDL. The PDDL domain is given below:

    ```pddl
    {pddl_domain}
    ```

    You will receive:
    1. A scene graph (JSON) describing all objects, surfaces, assets, and the \
    robot agent in the current workspace.
    2. A natural language subtask generated by a robot's planning module.
    3. A list of actions the PDDL description describes as allowed.
        These have the following format:
        ```json
        {{
          "name": <action name from pddl>,
          "parameters": <json list of pddl objects this action applies to, in order>
        }}
        ```
        Refer to the PDDL domain for the specifics of each action.

    You should translate the natural language task into the closest \
    approximation of the requested subtask, in PDDL form. Some color difference \
    is allowed -- for example, the user may specify to pick up a pink cube when \
    the scene graph only has red or blue cubes; in this case the red cube should \
    be chosen. You should be lenient with shades of color, \
    (accepting silver as white or grey as black, for example),
    but you should reject translations that have different hues (red vs blue) \
    or large differences in shade (white vs black).

    If the natural language task has errors such as garbled text or other nonsense, \
    you should reject the action.

    You should output a json object of this form:

    ```json
    {{
      "status": "SUCCESS" | "FAILURE"
      "reason": <specific reason for failure or choice of action>
      "chosen_action": <copy of the action to perform>
    }}
    ```

    If the status is FAILURE, you should omit chosen_action.

    """)

    TRANSLATOR_USER_TEMPLATE = textwrap.dedent("""\
    Scene Graph:
    {scene_graph_json}

    Subtask to translate: "{subtask}"

    Available actions:
    ```json
    {avail_actions}
    ```
    """)


    def verify_subtask(self, subtask: str) -> SubtaskVerificationResult:
        """
        Verify a single subtask against the current scene graph.

        Args:
            subtask: Natural language subtask from VLA.
            update_state: If True and the subtask is accepted, update the
                internal scene graph to the successor state.

        Returns:
            SubtaskVerificationResult with accept/reject and feedback.
        """

        return self.translate_subtask(subtask=subtask, scene_graph=self.scene_graph)
